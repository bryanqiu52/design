async function loadBlogContent(slug) {
    try {
        const resp = await fetch(`blog/posts/${slug}.md`);
        if (resp.ok) {
            return await resp.text();
        }
    } catch (e) {}
    const post = window.blogPosts.find(p => p.slug === slug);
    return post ? (post.content || '') : '';
}